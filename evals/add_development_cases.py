def main():
    initial = json.loads((ROOT / "data/relaydesk/development.json").read_text())
    cases = list(initial)
    for index, (
        category,
        subject,
        description,
        version,
        account,
        outcome,
        evidence,
        facts,
        tools,
    ) in enumerate(specifications, 11):
        case = {
            "id": f"dev-{index:02}",
            "category": category,
            "ticket": {
                "subject": subject,
                "description": description,
                "product_version": version,
                "account_id": account,
            },
            "expected_outcome": outcome,
            "required_evidence_ids": evidence,
            "required_facts": facts,
            "required_tools": tools,
        }
        if index == 30:
            case["tool_errors"] = ["get_service_health"]
        cases.append(case)
    (ROOT / "evals/development.json").write_text(json.dumps(cases, indent=2) + "\n")


if __name__ == "__main__":
    main()
